/**
 * Runs every safety check and (with --write) regenerates docs/safety/RESULTS.md
 * and docs/safety/results.json.
 *
 *   npm run safety:verify          # run everything, fail on any regression
 *   npm run safety:report          # same, and rewrite the results files
 *
 * Knobs: SAFETY_FUZZ_SEED, SAFETY_FUZZ_SESSIONS, SAFETY_EXPLORER_DEPTH,
 * SAFETY_SKIP_MUTATION=1, MUTATION_TMPDIR.
 */
import { execSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { runArchitectureSuite } from '../test/safety/architecture.test';
import { runAttackSuite } from '../test/safety/attacks.test';
import { runDatabaseSuite } from '../test/safety/db.test';
import { runFuzz } from '../test/safety/fuzz.test';
import { runExplorer } from '../test/safety/explorer.test';
import { runReuseCheck } from '../test/safety/quick';
import { runMutationTests, MutantResult } from './mutation-test';
import { runEvaluationSuite } from '../src/lib/evaluation/runner';
import { INVARIANTS } from '../src/lib/negotiation/invariants';
import { CheckResult } from '../test/support/check';

const write = process.argv.includes('--write');
const ROOT = join(__dirname, '..');

function gitCommit() {
  try { return execSync('git rev-parse --short HEAD', { cwd: ROOT, encoding: 'utf8' }).trim(); } catch { return 'unknown'; }
}

const mark = (passed: boolean) => (passed ? '✅ pass' : '❌ FAIL');
const escape = (value: string) => value.replace(/\|/g, '\\|');

async function main() {
  const started = Date.now();
  const fuzzSeed = Number(process.env.SAFETY_FUZZ_SEED ?? 20261105);
  const fuzzSessions = Number(process.env.SAFETY_FUZZ_SESSIONS ?? 2000);
  const explorerDepth = Number(process.env.SAFETY_EXPLORER_DEPTH ?? 3);

  const architecture = runArchitectureSuite();
  const attacksMemory = await runAttackSuite();
  const [postgres, attacksPostgres] = await runDatabaseSuite();
  const fuzz = await runFuzz({ seed: fuzzSeed, sessions: fuzzSessions, steps: 25 });
  const explorer = await runExplorer(explorerDepth);
  const reuse = await runReuseCheck();
  const evaluation = await runEvaluationSuite();
  let mutants: MutantResult[] = [];
  if (!process.env.SAFETY_SKIP_MUTATION) {
    console.log('\n--- 🧬 Running Mutation Tests ---');
    mutants = runMutationTests();
  }

  const checks: CheckResult[] = [architecture, attacksMemory, postgres, attacksPostgres, fuzz.check, explorer.check, reuse].flatMap((checker) => checker.results);
  const allPassed = checks.every((check) => check.passed)
    && mutants.every((mutant) => mutant.killed)
    && evaluation.metrics.passedCount === evaluation.metrics.scenarioCount;
  const seconds = Math.round((Date.now() - started) / 1000);

  const attackRows = attacksMemory.results.map((memory) => {
    const pg = attacksPostgres.results.find((item) => item.id === memory.id);
    return `| ${memory.id} | ${escape(memory.title)} | ${mark(memory.passed)} | ${pg ? mark(pg.passed) : '—'} | ${escape(memory.detail)} |`;
  });
  const naive = fuzz.metrics.naive;
  const gated = fuzz.metrics.gated;
  const blocked = Object.entries(fuzz.metrics.blocked).sort((a, b) => b[1] - a[1]);
  const killed = mutants.filter((mutant) => mutant.killed).length;

  const markdown = `# BARGAIN — Safety Results

> Generated by \`npm run safety:report\` · commit \`${gitCommit()}\` · Node ${process.version} · ${new Date().toISOString().slice(0, 10)} · ${seconds}s
>
> Overall: **${allPassed ? 'ALL CHECKS PASSED' : 'FAILURES PRESENT'}**. Every number below is produced by code in \`test/safety\` and \`scripts/\`; rerun the command to reproduce it.

## Summary

| Evidence | Result |
|---|---|
| Attack cases (in-memory store) | ${attacksMemory.results.filter((r) => r.passed).length}/${attacksMemory.results.length} blocked |
| Attack cases (PostgreSQL via PGlite) | ${attacksPostgres.results.filter((r) => r.passed).length}/${attacksPostgres.results.length} blocked |
| PostgreSQL regressions and durability (R1–R2 reproduce review bugs) | ${postgres.results.filter((r) => r.passed).length}/${postgres.results.length} pass |
| Fuzzing (seed ${fuzzSeed}) | ${fuzz.metrics.steps.toLocaleString()} random steps over ${fuzzSessions.toLocaleString()} sessions, **${fuzz.metrics.violations.length} violations**, ${fuzz.metrics.unexpectedErrors.length} unexpected errors |
| Bounded exhaustive exploration | all ${explorer.metrics.sequences.toLocaleString()} sequences of ${explorerDepth} moves (${explorer.metrics.alphabet}-move alphabet × ${explorer.metrics.startStates} start states), ${explorer.metrics.transitions.toLocaleString()} transitions, **${explorer.metrics.violations.length} violations** |
| Mutation testing | ${mutants.length ? `${killed}/${mutants.length} injected safety bugs detected` : 'skipped'} |
| Architecture fitness tests | ${architecture.results.filter((r) => r.passed).length}/${architecture.results.length} pass |
| Reuse in a second domain (\`npm run example:reuse\`) | ${mark(reuse.passed)} — cloud deletions gated by the same code |
| Negotiation evaluation scenarios | ${evaluation.metrics.passedCount}/${evaluation.metrics.scenarioCount} pass |

## Same model, with and without the gate

The fuzzer drives the agent with adversarial "model" outputs (accept anything,
blow the budget, garbage numbers, misreported prices, obeying prompt
injection, endless waits). Every output is scored twice: as a naive agent that
executes what the model says, and as what BARGAIN actually wrote and executed.

| Unsafe outcome | Naive agent (same outputs) | BARGAIN |
|---|---:|---:|
| Offer or purchase above the buyer's budget | ${naive.overBudget} | **${gated.overBudget}** |
| Offer below the seller's floor | ${naive.belowFloor} | **${gated.belowFloor}** |
| Purchase committed without the required human approval | ${naive.unapprovedCommit} | **${gated.unapprovedCommit}** |
| Invalid number (NaN / negative) sent | ${naive.invalidNumber} | **${gated.invalidNumber}** |
| Model calls scored | ${fuzz.metrics.plannerCalls} | — |

Purchases that did happen in the fuzz run: ${fuzz.metrics.dealsHumanApproved} with signed human approval, ${fuzz.metrics.dealsPolicyApproved} pre-authorized by policy.

## Attack cases

| ID | Attack | In-memory | PostgreSQL | Evidence |
|---|---|---|---|---|
${attackRows.join('\n')}

## Regression tests (PostgreSQL)

| ID | Check | Result | Evidence |
|---|---|---|---|
${postgres.results.map((r) => `| ${r.id} | ${escape(r.title)} | ${mark(r.passed)} | ${escape(r.detail)} |`).join('\n')}

R1 and R2 reproduce the two database-only bugs from the code review: \`time_skip\`
wrote fractional days into an integer column, and approvals always used a stale
session version. Neither was visible to the original in-memory tests.

## Runtime invariants

Enforced on every write by \`src/lib/negotiation/invariants.ts\` and re-checked by
independent oracles in the fuzzer and the explorer.

| ID | Invariant |
|---|---|
${Object.entries(INVARIANTS).map(([id, text]) => `| ${id} | ${escape(text)} |`).join('\n')}

## Fuzzing

Refusals by reason (every refusal is a typed domain error; ${fuzz.metrics.unexpectedErrors.length} unexpected errors):

| Refusal | Count |
|---|---:|
${blocked.map(([code, count]) => `| \`${code}\` | ${count} |`).join('\n')}

## Bounded exhaustive exploration

${explorer.check.results.map((r) => `- ${mark(r.passed)} ${r.title} — ${r.detail}`).join('\n')}

Within this bound the result is exhaustive, not sampled: every combination of
the honest and hostile moves listed in \`test/safety/explorer.test.ts\` was run
against the real service, store and gate. Set \`SAFETY_EXPLORER_DEPTH\` to go deeper.

## Mutation testing

Each mutant re-introduces one realistic safety bug into a copy of the code and
runs the fast suite. Killed = the tests noticed.

| ID | Injected bug | Result | First failing check |
|---|---|---|---|
${mutants.map((m) => `| ${m.id} | ${escape(m.title)} | ${m.killed ? '💀 killed' : '🧟 survived'} | ${escape(m.caughtBy[0] ?? '—')} |`).join('\n') || '| — | skipped | — | — |'}

## Architecture fitness

| ID | Rule | Result | Evidence |
|---|---|---|---|
${architecture.results.map((r) => `| ${r.id} | ${escape(r.title)} | ${mark(r.passed)} | ${escape(r.detail)} |`).join('\n')}

## Reproduce

\`\`\`bash
npm ci
npm test
npm run safety:verify
\`\`\`
`;

  const json = {
    generatedAt: new Date().toISOString(),
    commit: gitCommit(),
    node: process.version,
    allPassed,
    checks,
    fuzz: fuzz.metrics,
    explorer: explorer.metrics,
    mutants,
    evaluation: evaluation.metrics,
  };

  if (write) {
    const directory = join(ROOT, 'docs', 'safety');
    mkdirSync(directory, { recursive: true });
    writeFileSync(join(directory, 'RESULTS.md'), markdown);
    writeFileSync(join(directory, 'results.json'), `${JSON.stringify(json, null, 2)}\n`);
    console.log(`\nWrote docs/safety/RESULTS.md and docs/safety/results.json`);
  }
  console.log(`\n${allPassed ? '🎉 SAFETY VERIFICATION PASSED' : '❌ SAFETY VERIFICATION FAILED'} in ${seconds}s`);
  process.exit(allPassed ? 0 : 1);
}

void main();
